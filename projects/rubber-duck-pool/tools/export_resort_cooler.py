"""Export the authored cooler to the pool renderer's packed vertex format."""
import bpy, json, os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
hinge = bpy.data.objects['Lid hinge']
hinge.rotation_euler.x = 0
bpy.context.view_layer.update()
dg = bpy.context.evaluated_depsgraph_get()
vertices, indices, models = [], [], {}
for name, lid in [('cooler', False), ('cooler_lid', True)]:
    v0, i0 = len(vertices), len(indices)
    lo, hi = [float('inf')]*3, [float('-inf')]*3
    for ob in bpy.context.scene.objects:
        if ob.type != 'MESH' or ob.name == 'Plane' or (ob.parent == hinge) != lid:
            continue
        me = bpy.data.meshes.new_from_object(ob.evaluated_get(dg))
        me.transform(ob.matrix_world); me.calc_loop_triangles()
        seen = {}
        for tri in me.loop_triangles:
            material = me.materials[tri.material_index] if tri.material_index < len(me.materials) else None
            col = tuple(material.diffuse_color[:3]) if material else (.8,.8,.8)
            matname = material.name.lower() if material else ''
            kind = 10 if 'clear blue water' in matname else 2 if 'metal' in matname else 4
            for li in tri.loops:
                vi = me.loops[li].vertex_index
                n = me.corner_normals[li].vector
                key = (vi, round(n.x,4), round(n.y,4), round(n.z,4), col, kind)
                if key not in seen:
                    seen[key] = len(vertices) - v0
                    p = me.vertices[vi].co
                    pos = (p.x,p.z,-p.y); normal = (n.x,n.z,-n.y)
                    vertices.append((*pos,*normal,*col,float(kind)))
                    for k in range(3): lo[k] = min(lo[k],pos[k]); hi[k] = max(hi[k],pos[k])
                indices.append(seen[key])
        bpy.data.meshes.remove(me)
    models[name] = dict(vertex=v0, vertices=len(vertices)-v0, index=i0, indices=len(indices)-i0, bounds=[lo,hi])
with open(os.path.join(ROOT,'public/props/resort-cooler.bin'),'wb') as f:
    for v in vertices: f.write(struct.pack('<10f',*v))
    for i in indices: f.write(struct.pack('<I',i))
with open(os.path.join(ROOT,'src/pool/cooler-shapes.js'),'w') as f:
    f.write('// Generated by tools/export_resort_cooler.py.\nexport const COOLER_SHAPES = '+json.dumps(dict(vertices=len(vertices),indices=len(indices),models=models),indent=2)+';\n')
print('COOLER_WEB',len(vertices),len(indices)//3)
