"""Export the open deck-chair-atelier-v5.blend to the pool's packed mesh format."""
import os
import bpy, math, struct, json
from mathutils import Vector
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scene=bpy.context.scene
for ob in scene.objects:
    if ob.name=='Studio floor': continue
    for mod in ob.modifiers:
        if mod.type=='BEVEL': mod.segments=1 if ob.name.startswith('Canvas seam stitch') else 2
    if ob.type=='CURVE': ob.data.bevel_resolution=1
bpy.context.view_layer.update()
dg=bpy.context.evaluated_depsgraph_get(); scale=.55
verts=[]; inds=[]; lo=[1e9]*3; hi=[-1e9]*3
for ob in scene.objects:
    if ob.type not in {'MESH','CURVE'} or ob.name=='Studio floor': continue
    evaluated=ob.evaluated_get(dg); me=bpy.data.meshes.new_from_object(evaluated); me.transform(ob.matrix_world); me.calc_loop_triangles()
    seen={}
    for tri in me.loop_triangles:
        material=me.materials[tri.material_index] if tri.material_index<len(me.materials) else None
        name=material.name if material else ''
        if 'Lagoon' in name: col=(0.,0.,0.); kind=7
        elif 'white canvas' in name.lower(): col=(.91,.90,.84); kind=3
        elif 'Canvas stitching' in name: col=(.72,.72,.62); kind=3
        elif 'steel' in name.lower(): col=(.35,.39,.4); kind=2
        elif 'brass' in name.lower(): col=(.67,.39,.10); kind=2
        else: col=(.70,.48,.27); kind=1
        col=tuple(c/12.92 if c<=.04045 else ((c+.055)/1.055)**2.4 for c in col)
        for li in tri.loops:
            vi=me.loops[li].vertex_index; n=me.corner_normals[li].vector; key=(vi,round(n.x,4),round(n.y,4),round(n.z,4),kind,col)
            if key not in seen:
                seen[key]=len(verts); p=me.vertices[vi].co; pos=(p.x*scale,p.z*scale,-p.y*scale); normal=(n.x,n.z,-n.y)
                verts.append((*pos,*normal,*col,float(kind)))
                for k in range(3): lo[k]=min(lo[k],pos[k]); hi[k]=max(hi[k],pos[k])
            inds.append(seen[key])
    bpy.data.meshes.remove(me)
with open(os.path.join(ROOT, 'public/props/resort-chair.bin'),'wb') as f:
    for v in verts: f.write(struct.pack('<10f',*v))
    for i in inds: f.write(struct.pack('<I',i))
shape={'vertices':len(verts),'indices':len(inds),'models':{'chair':{'vertex':0,'vertices':len(verts),'index':0,'indices':len(inds),'bounds':[lo,hi]}}}
with open(os.path.join(ROOT, 'src/pool/chair-shapes.js'),'w') as f:
    f.write('// Generated by tools/export_resort_chair.py from the Blender chair.\nexport const CHAIR_SHAPES = '+json.dumps(shape,indent=2)+';\n')
print('CHAIR_GAME',len(verts),len(inds)//3,'triangles',lo,hi)
